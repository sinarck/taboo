// Get a shuffled deck of cards, excluding already-used words
// Uses array-shuffle (Durstenfeld/Fisher-Yates algorithm) for optimal randomization
export function getRandomCards(count: number, usedWords?: Set<string>): TabooCard[] {
  // Filter out cards with used words
  let availableCards = usedWords && usedWords.size > 0
    ? tabooCards.filter(card => !usedWords.has(card.word))
    : [...tabooCards]
  
  // If we've used all cards, reset and use full deck
  if (availableCards.length === 0) {
    availableCards = [...tabooCards]
  }
  
  // Shuffle using proven Durstenfeld algorithm via array-shuffle library
  const shuffledCards = arrayShuffle(availableCards)
  
  // Take the requested count (or all if less available)
  return shuffledCards.slice(0, Math.min(count, shuffledCards.length))
}

// Get total card count for display
export function getTotalCardCount(): number {
  return tabooCards.length
}
